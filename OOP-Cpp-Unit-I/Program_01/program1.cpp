#include <iostream>  // Input/output library
using namespace std; // Standard namespace

int main() { // Main entry point
    int roll = 101;        // Roll number
    char grade = 'A';      // Grade character
    float fee = 12500.50; // Fee amount

    cout << "Roll No: " << roll << endl; // Print roll
    cout << "Grade: " << grade << endl;   // Print grade
    cout << "Fee: " << fee << endl;       // Print fee

    return 0; // Exit program
}

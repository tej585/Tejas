// Program 1: Basic Data Types

#include <iostream>      // i/o lib

using namespace std;     // use std ns

int main() {             // main fn

	int roll = 101;          // int → roll no
	char grade = 'A';        // char → grade
	float fee = 12500.50;    // float → fee

	cout << "Roll No: " << roll << endl; // disp roll
	cout << "Grade: " << grade << endl;  // disp grade
	cout << "Fee: " << fee << endl;      // disp fee

	return 0;               // end prog
}